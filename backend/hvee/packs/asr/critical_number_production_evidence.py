"""Production-derived evidence contracts for Critical Number Fidelity v1.

This module seals privacy-preserving evidence that was selected from a
production source.  It stores opaque identifiers, commitments, timestamps,
and caller attestations only.  Raw audio, transcripts, PII, linkage secrets,
and legal or privacy conclusions remain outside HVEE.

Cross-set linkage tokens are generated by callers with a caller-managed
HMAC-SHA256 key.  HVEE validates and compares the opaque tokens but never
accepts, derives, or retains that key.  A successful verification is
evaluator-development evidence only: it does not issue certification, qualify
the evaluator for production, modify a release verdict, or enable release
enforcement.
"""

